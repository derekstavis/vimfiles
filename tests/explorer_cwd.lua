local api = require('nvim-tree.api')
local original_tab = vim.api.nvim_get_current_tabpage()
local original_cwd = vim.fn.getcwd(-1, 0)
local temp = vim.fn.tempname()
local a, b, c = temp .. '/project one', temp .. '/project two', temp .. '/project three'
for _, dir in ipairs({ a, b, c }) do
  vim.fn.mkdir(dir, 'p')
  vim.fn.writefile({ dir }, dir .. '/file.txt')
end
local function cd(dir) vim.cmd.tcd(vim.fn.fnameescape(dir)) end
local function same_dir(left, right) return vim.uv.fs_realpath(left) == vim.uv.fs_realpath(right) end
local function root_is(dir)
  return vim.wait(2000, function()
    local root = api.tree.get_nodes()
    return root and root.absolute_path == vim.uv.fs_realpath(dir)
  end, 10)
end
cd(a)
api.tree.open()
assert(root_is(a), 'Tree must open at the active tab cwd')
local first_tree = api.tree.winid()
vim.cmd.wincmd('p')
vim.cmd.tabnew()
local other_tab = vim.api.nvim_get_current_tabpage()
cd(b)
local editor = vim.api.nvim_get_current_win()
assert(root_is(b), 'Changing tab cwd must update the shared tree root')
assert(vim.wait(2000, api.tree.is_visible, 10), 'An open sidebar must follow to the new tab')
assert(vim.api.nvim_get_current_win() == editor, 'Updating the tree must preserve editor focus')
assert(same_dir(vim.fn.getcwd(-1, 0), b), 'Tree updates must not change the tab cwd')

-- A window-local directory must not override the active tab's project.
vim.cmd.lcd(vim.fn.fnameescape(c))
vim.wait(50)
assert(root_is(b), 'Window-local cwd must not replace the tab cwd')
assert(same_dir(vim.fn.getcwd(), c), 'Tree synchronization must preserve window-local cwd')

vim.api.nvim_set_current_tabpage(original_tab)
assert(root_is(a), 'Returning to a tab must restore its cwd as the tree root')
assert(api.tree.winid() == first_tree, 'Returning must reuse the existing sidebar window')
cd(c)
assert(root_is(c), 'A visible tree must follow subsequent :tcd changes')
api.tree.close()
cd(a)
assert(root_is(a), 'A hidden tree must follow cwd changes without reopening')
assert(not api.tree.is_visible(), 'Changing cwd must not open a closed sidebar')
api.tree.open()
assert(root_is(a), 'Reopening must use the latest tab cwd')

vim.api.nvim_set_current_tabpage(other_tab)
assert(root_is(b), 'Changing another tab cwd must leave this tab cwd intact')
api.tree.close()
vim.cmd.tabclose()
assert(vim.api.nvim_get_current_tabpage() == original_tab)
assert(root_is(a), 'Closing a tab must restore the remaining tab root')
api.tree.close()
cd(original_cwd)
assert(root_is(original_cwd), 'Restore the original cwd')
vim.fn.delete(temp, 'rf')
print('PASS: explorer follows tab cwd across switching, :tcd, :lcd, and close/reopen')
